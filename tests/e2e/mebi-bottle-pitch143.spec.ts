import { expect, test } from "@playwright/test";
import { bottleBlowTitle, bottlePitchExample, bottlePitchTitle, bottleStrikeTitle } from "../../src/learning/mebiBottlePitch";
import { learning, openCourse, prepare, storage } from "./helpers/revisedCourse";
import { svgLayoutAudit } from "./helpers/svgAudit";

test("ses modeli su miktarıyla vurma ve üflemede ters yöne değişir", async ({ page, context }, info) => {
  await page.setViewportSize({ width: 320, height: 870 });
  await prepare(page, true);
  const before = learning(await storage(page));
  await context.setOffline(true);
  await openCourse(page, { lesson: "ses-deprem-dalgalari", search: "Ses ve deprem" });
  const toc = page.getByRole("navigation", { name: "Anlatım içeriği", exact: true });
  const item = toc.getByRole("button", { name: bottlePitchTitle, exact: true });
  if (!(await item.isVisible())) await toc.getByText("İçindekiler", { exact: true }).press("Enter");
  await item.press("Enter");
  const scope = `figure[data-section-figure="${bottlePitchTitle}"]`;
  const figure = page.locator(scope);
  const svg = figure.getByRole("img");
  await expect(svg).toHaveAccessibleName(/soldaki boş.*sağdaki su seviyesi/i);
  await expect(figure).toContainText("Su eklenen şişe: 0,82 kat frekans.");
  const fill = figure.getByRole("slider", { name: "Sağ şişedeki su", exact: true });
  await fill.press("Home");
  await expect(figure).toContainText("Su eklenen şişe: 1 kat frekans.");
  await fill.press("End");
  await expect(figure).toContainText("Su eklenen şişe: 0,77 kat frekans.");
  await svg.evaluate(node => node.scrollIntoView({ block: "center", inline: "nearest" }));
  await svg.screenshot({ path: info.outputPath("bottle-strike-143.png") });
  await figure.getByRole("button", { name: "İleri", exact: true }).press("Enter");
  await expect(figure).toContainText("Üfleme: su üstündeki hava titreşir.");
  await expect(figure).toContainText("Su eklenen şişe: 1,83 kat frekans.");
  await expect(figure).toContainText("hava hacminin %30 kadarı kaldı.");
  await svg.evaluate(node => node.scrollIntoView({ block: "center", inline: "nearest" }));
  await svg.screenshot({ path: info.outputPath("bottle-blow-143.png") });
  expect((await page.evaluate(svgLayoutAudit, { scope, figuresOnly: true, explore: true })).issues).toEqual([]);
  expect(learning(await storage(page))).toEqual(before);
});

test("Kopya Kağıdı yarı dolu şişeyi iki farklı çözüm çiziminde gösterir", async ({ page, context }) => {
  await prepare(page);
  await context.setOffline(true);
  await page.goto("/#/cheatsheets?topic=detail-130");
  const example = page.locator(".cheat-examples .worked-example").filter({ hasText: bottlePitchExample.title });
  await example.locator(":scope > summary").press("Enter");
  const solution = example.locator(".cheat-solution");
  await expect(solution.getByRole("img")).toHaveCount(0);
  await solution.locator("summary").press("Enter");
  const struck = solution.locator(`figure[data-section-figure="${bottleStrikeTitle}"]`);
  const blown = solution.locator(`figure[data-section-figure="${bottleBlowTitle}"]`);
  await expect(struck).toContainText("0,82 kat frekans");
  await expect(blown).toContainText("1,41 kat frekans");
  await expect(struck.getByRole("slider")).toHaveCount(0);
  await expect(blown.getByRole("slider")).toHaveCount(0);
});
