import { expect, test } from "@playwright/test";
import { sonarDepthTitle, sonarExample, sonarPulseTitle, sonarTitle } from "../../src/learning/mebiSonar";
import { learning, openCourse, prepare, storage } from "./helpers/revisedCourse";
import { svgLayoutAudit } from "./helpers/svgAudit";

test("tekne, balık sürüsü ve iki ses yönü çevrimdışı aynı gecikme ölçeğini kullanır", async ({ page, context }, info) => {
  await page.setViewportSize({ width: 320, height: 870 });
  await prepare(page, true);
  const before = learning(await storage(page));
  await context.setOffline(true);
  await openCourse(page, { lesson: "ses-deprem-dalgalari", search: "Ses ve deprem" });
  const toc = page.getByRole("navigation", { name: "Anlatım içeriği", exact: true });
  const item = toc.getByRole("button", { name: sonarTitle, exact: true });
  if (!(await item.isVisible())) await toc.getByText("İçindekiler", { exact: true }).press("Enter");
  await item.press("Enter");
  const scope = `figure[data-section-figure="${sonarTitle}"]`;
  const figure = page.locator(scope);
  const svg = figure.getByRole("img");
  await expect(svg.getByText("Tekne", { exact: true })).toBeVisible();
  await expect(svg.getByText("Balık sürüsü", { exact: true })).toBeVisible();
  await expect(svg.getByText("Dönüş", { exact: true })).toHaveCount(0);
  await figure.getByRole("button", { name: "İleri", exact: true }).press("Enter");
  await expect(svg.getByText("Dönüş", { exact: true })).toBeVisible();
  await expect(figure).toContainText("düşey uzaklık 90 m.");
  const delay = figure.getByRole("slider", { name: "Sonar gidiş-dönüş süresi", exact: true });
  await delay.press("Home");
  await expect(figure).toContainText("düşey uzaklık 30 m.");
  await delay.press("End");
  await expect(figure).toContainText("düşey uzaklık 120 m.");
  await svg.evaluate(node => node.scrollIntoView({ block: "center" }));
  await svg.screenshot({ path: info.outputPath("sonar-return152.png") });
  expect((await page.evaluate(svgLayoutAudit, { scope, figuresOnly: true, explore: true })).issues).toEqual([]);
  expect(learning(await storage(page))).toEqual(before);
});

test("Kopya Kağıdı sonar yolunu ve süre hesabını kendi iki görselinde açar", async ({ page, context }) => {
  await prepare(page);
  await context.setOffline(true);
  await page.goto("/#/cheatsheets?topic=detail-130");
  const section = page.locator(".cheat-section").filter({ has: page.getByRole("heading", { name: sonarTitle, exact: true }) });
  await expect(section.getByRole("row", { name: "120 90", exact: true })).toBeVisible();
  const example = page.locator(".cheat-examples .worked-example").filter({ hasText: sonarExample.title });
  await example.locator(":scope > summary").press("Enter");
  const solution = example.locator(".cheat-solution");
  await expect(solution.getByRole("img")).toHaveCount(0);
  await solution.locator("summary").press("Enter");
  const outgoing = solution.locator(`figure[data-section-figure="${sonarPulseTitle}"]`);
  await expect(outgoing.getByRole("img").getByText("Dönüş", { exact: true })).toHaveCount(0);
  const depth = solution.locator(`figure[data-section-figure="${sonarDepthTitle}"]`);
  await expect(depth.getByRole("img").getByText("90 m", { exact: true })).toBeVisible();
});
